div_res = num1 / num2
rem_res = num1 % num2

print(f"Sum: {add_res}")
print(f"Difference: {sub_res}")
print(f"Product: {mul_res}")
print(f"Quotient: {div_res}")
print(f"Remainder: {rem_res}")
